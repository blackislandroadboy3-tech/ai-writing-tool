"""各ライティング機能のプロンプト定義。

各ツールは build(inputs) -> (system, user) を返す。
"""

BASE_SYSTEM = (
    "あなたは日本語のプロのライターです。"
    "依頼された文章だけを出力し、前置き（「承知しました」など）や後書きの解説は付けないでください。"
    "出力はMarkdownで整形してください。"
)

TONES = ["ていねい", "フレンドリー", "フォーマル", "カジュアル", "熱意のある", "落ち着いた"]


def blog(i):
    user = f"""次の条件でブログ記事を書いてください。

- テーマ: {i['theme']}
- 想定読者: {i['audience'] or '一般読者'}
- 含めたいキーワード: {i['keywords'] or '特になし'}
- 文字数の目安: 約{i['length']}文字
- トーン: {i['tone']}
- 補足・盛り込みたい内容: {i['notes'] or '特になし'}

構成:
1. 読者の興味を引くタイトル（# 見出し）
2. 導入文
3. ## 見出しで区切った本文（必要に応じて ### 小見出し・箇条書き）
4. まとめ"""
    return BASE_SYSTEM, user


def email_reply(i):
    user = f"""次の受信メールへの返信文を作成してください。

## 受信メール
{i['received']}

## 返信の方針
{i['intent'] or '内容に適切に応じる'}

## 条件
- 相手との関係: {i['relation']}
- トーン: {i['tone']}
- 差出人名（署名）: {i['sender'] or '（署名は「〇〇」としてください）'}

件名（「件名: 」で始まる1行）と本文を出力してください。"""
    return BASE_SYSTEM, user


SUMMARY_STYLES = {
    "3行要約": "要点を3行（3文）にまとめてください。",
    "箇条書き": "重要なポイントを箇条書き（5〜8項目程度）でまとめてください。",
    "詳しめ": "見出しを付けて、内容を網羅的かつ簡潔に要約してください。",
    "一言で": "内容を1文で要約してください。",
}


def summarize(i):
    user = f"""次の文章を要約してください。{SUMMARY_STYLES[i['style']]}

<text>
{i['text']}
</text>"""
    return BASE_SYSTEM, user


REWRITE_MODES = {
    "校正（誤字脱字・文法）": "誤字脱字・文法・表記ゆれを直してください。内容と文体はできるだけ保ってください。修正後の文章を出力し、最後に「## 主な修正点」として箇条書きで修正箇所を示してください。",
    "読みやすく": "意味を変えずに、より読みやすく自然な文章に書き直してください。",
    "フォーマルに": "ビジネスにふさわしいフォーマルな文体に書き直してください。",
    "カジュアルに": "親しみやすいカジュアルな文体に書き直してください。",
    "短く": "要点を保ったまま、できるだけ簡潔に短く書き直してください。",
    "詳しく": "内容を補足・具体化して、より詳しい文章に書き直してください。",
}


def rewrite(i):
    user = f"""次の文章を書き直してください。{REWRITE_MODES[i['mode']]}

<text>
{i['text']}
</text>"""
    return BASE_SYSTEM, user


SNS_PLATFORMS = {
    "X（Twitter）": "全角140文字以内。ハッシュタグは2〜3個。",
    "Instagram": "絵文字を適度に使い、改行で読みやすく。最後にハッシュタグを10個程度。",
    "LinkedIn": "ビジネス向け。300〜600文字程度で、学びや示唆が伝わるように。",
    "Facebook": "親しみやすく、200〜400文字程度。",
    "Threads": "500文字以内の会話調。",
}


def sns(i):
    user = f"""{i['platform']}向けの投稿文を{i['count']}パターン作成してください。

- 投稿内容: {i['topic']}
- トーン: {i['tone']}
- プラットフォームのルール: {SNS_PLATFORMS[i['platform']]}

各パターンは「## パターン1」のように見出しを付けて出力してください。"""
    return BASE_SYSTEM, user


def translate(i):
    user = f"""次の文章を{i['target']}に翻訳してください。直訳ではなく、{i['target']}として自然な表現にしてください。翻訳文のみを出力してください。

<text>
{i['text']}
</text>"""
    return BASE_SYSTEM, user


COPY_KINDS = ["記事タイトル", "キャッチコピー", "商品説明文", "YouTube動画タイトル", "メール件名"]


def copywriting(i):
    user = f"""次の内容について「{i['kind']}」の案を{i['count']}個作成してください。

- 内容: {i['topic']}
- ターゲット: {i['audience'] or '一般'}
- トーン: {i['tone']}

番号付きリストで出力し、各案の後ろに（ねらい: 〜）と短く添えてください。"""
    return BASE_SYSTEM, user


def free(i):
    return "あなたは日本語のプロのライターです。出力はMarkdownで整形してください。", i["request"]


TOOLS = {
    "📝 ブログ記事": blog,
    "✉️ メール返信": email_reply,
    "📄 要約": summarize,
    "✏️ 校正・リライト": rewrite,
    "📱 SNS投稿": sns,
    "🌐 翻訳": translate,
    "💡 タイトル・キャッチコピー": copywriting,
    "💬 自由リクエスト": free,
}
